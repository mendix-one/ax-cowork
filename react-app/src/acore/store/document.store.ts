import { makeAutoObservable } from 'mobx'
import { readJson, writeJson } from '@/acore/storage'

export type Doc = {
  id: string
  title: string
  source: string
  updatedAt: number
}

const STORAGE_KEY = 'ax-documents'

function isDoc(v: unknown): v is Doc {
  if (typeof v !== 'object' || v === null) return false
  const d = v as Record<string, unknown>
  return typeof d.id === 'string' && typeof d.title === 'string' && typeof d.source === 'string' && typeof d.updatedAt === 'number'
}

function isDocArray(v: unknown): v is Doc[] {
  return Array.isArray(v) && v.every(isDoc)
}

