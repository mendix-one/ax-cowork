export class DocumentStore {
  // Hydrate from localStorage if a valid persisted array exists; otherwise
  // start with the seed doc so the demo URL /docs/demo always works.
  docs: Doc[] = readJson(STORAGE_KEY, isDocArray) ?? [DEMO_DOC]

  constructor() {
    makeAutoObservable(this)
  }

  getById(id: string): Doc | undefined {
    return this.docs.find((d) => d.id === id)
  }

  setSource(id: string, source: string) {
    const doc = this.getById(id)
    if (!doc) return
    doc.source = source
    doc.updatedAt = Date.now()
    writeJson(STORAGE_KEY, this.docs)
  }
}
